#!/usr/bin/env python3
import argparse
import json
import os
import re
from typing import Any, Dict, List

import pandas as pd
import numpy as np

from verl.utils.reward_score import _default_compute_score


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Analyze Stage-1 extreme generalization predictions.")
    parser.add_argument(
        "--pred_parquet",
        nargs="+",
        required=True,
        help="One or multiple prediction parquet paths generated by passk.sh.",
    )
    parser.add_argument(
        "--out_csv",
        required=True,
        help="Output CSV path for summary-by-depth table (e.g., results/stage1_generalization/summary_by_depth.csv).",
    )
    parser.add_argument(
        "--k",
        type=int,
        default=32,
        help="k for pass@k computation from responses list.",
    )
    parser.add_argument("--wandb_project", type=str, default=None, help="Optional W&B project for logging summaries.")
    parser.add_argument("--wandb_entity", type=str, default=None, help="Optional W&B entity/team.")
    parser.add_argument("--wandb_run_name", type=str, default=None, help="Optional W&B run name.")
    parser.add_argument("--wandb_group", type=str, default=None, help="Optional W&B run group.")
    parser.add_argument("--wandb_tags", type=str, default="", help="Optional comma-separated W&B tags.")
    return parser.parse_args()


def _to_float_score(score: Any) -> float:
    if isinstance(score, (int, float, bool)):
        return float(score)
    if isinstance(score, (tuple, list)):
        if len(score) >= 2 and isinstance(score[1], (int, float, bool)):
            return float(score[1])
        if len(score) >= 1 and isinstance(score[0], (int, float, bool)):
            return float(score[0])
        return 0.0
    try:
        return float(score)
    except Exception:
        return 0.0


def _safe_parse_json(value: Any) -> Dict[str, Any]:
    if isinstance(value, dict):
        return value
    if isinstance(value, str):
        try:
            return json.loads(value)
        except Exception:
            return {}
    return {}


def _extract_ground_truth(reward_model: Any) -> Any:
    if isinstance(reward_model, dict):
        return reward_model.get("ground_truth")
    if isinstance(reward_model, str):
        try:
            parsed = json.loads(reward_model)
            if isinstance(parsed, dict):
                return parsed.get("ground_truth")
        except Exception:
            return None
    return None


def _extract_depth(row: Dict[str, Any]) -> int:
    extra = row.get("extra_info")
    extra_obj = _safe_parse_json(extra)
    depth = extra_obj.get("depth")
    if isinstance(depth, int):
        return depth

    data_source = str(row.get("data_source", ""))
    match = re.search(r"depth(\d+)", data_source)
    if match:
        return int(match.group(1))
    return -1


def _extract_expr_node_count(row: Dict[str, Any]) -> int:
    extra = row.get("extra_info")
    extra_obj = _safe_parse_json(extra)
    value = extra_obj.get("expr_node_count")
    if isinstance(value, int):
        return value
    try:
        return int(value)
    except Exception:
        return -1


def _extract_ref_code(ground_truth: Any) -> str:
    gt_obj = _safe_parse_json(ground_truth)
    code = gt_obj.get("ref_code", "")
    return code if isinstance(code, str) else ""


def _structure_bucket(ref_code: str) -> str:
    plus_count = ref_code.count("+")
    interlace_count = len(re.findall(r"func_7\s*\(", ref_code))
    recursive_interlace_count = len(re.findall(r"func_20\s*\(", ref_code))
    binary_comp_count = plus_count + interlace_count + recursive_interlace_count

    if binary_comp_count == 0:
        return "linear"
    if binary_comp_count == 1:
        return "mixed"
    return "branching"


def _compute_scores(data_source: str, ground_truth: Any, responses: Any, k: int) -> Dict[str, float]:
    if isinstance(responses, np.ndarray):
        responses = responses.tolist()
    elif isinstance(responses, tuple):
        responses = list(responses)

    if not isinstance(responses, list):
        if responses is None:
            responses = []
        else:
            responses = [responses]

    scores: List[float] = []
    for resp in responses:
        try:
            raw = _default_compute_score(data_source, resp, ground_truth)
            scores.append(_to_float_score(raw))
        except Exception:
            scores.append(0.0)

    if not scores:
        return {"pass_at_1": 0.0, "pass_at_k": 0.0}

    pass_at_1 = 1.0 if scores[0] >= 1.0 else 0.0
    pass_at_k = 1.0 if any(s >= 1.0 for s in scores[: max(k, 1)]) else 0.0
    return {"pass_at_1": pass_at_1, "pass_at_k": pass_at_k}


def main() -> None:
    args = parse_args()
    records: List[Dict[str, Any]] = []

    for parquet_path in args.pred_parquet:
        df = pd.read_parquet(parquet_path)
        for row in df.to_dict(orient="records"):
            data_source = str(row.get("data_source", ""))
            reward_model = row.get("reward_model")
            ground_truth = _extract_ground_truth(reward_model)
            depth = _extract_depth(row)
            ref_code = _extract_ref_code(ground_truth)
            bucket = _structure_bucket(ref_code)
            metrics = _compute_scores(data_source, ground_truth, row.get("responses"), args.k)

            records.append(
                {
                    "source_file": parquet_path,
                    "depth": depth,
                    "expr_node_count": _extract_expr_node_count(row),
                    "structure_bucket": bucket,
                    "pass_at_1": metrics["pass_at_1"],
                    "pass_at_k": metrics["pass_at_k"],
                }
            )

    result_df = pd.DataFrame.from_records(records)
    if result_df.empty:
        raise RuntimeError("No records were loaded from --pred_parquet inputs.")

    summary_by_depth = (
        result_df.groupby("depth", as_index=False)
        .agg(samples=("pass_at_1", "size"), pass_at_1=("pass_at_1", "mean"), pass_at_k=("pass_at_k", "mean"))
        .sort_values("depth")
    )

    bucket_order = {"linear": 0, "mixed": 1, "branching": 2}
    summary_by_structure = (
        result_df.groupby("structure_bucket", as_index=False)
        .agg(samples=("pass_at_1", "size"), pass_at_1=("pass_at_1", "mean"), pass_at_k=("pass_at_k", "mean"))
    )
    summary_by_structure["bucket_order"] = summary_by_structure["structure_bucket"].map(bucket_order).fillna(999)
    summary_by_structure = summary_by_structure.sort_values("bucket_order").drop(columns=["bucket_order"])

    summary_by_node_count = (
        result_df.groupby("expr_node_count", as_index=False)
        .agg(samples=("pass_at_1", "size"), pass_at_1=("pass_at_1", "mean"), pass_at_k=("pass_at_k", "mean"))
        .sort_values("expr_node_count")
    )

    overall = {
        "num_records": int(len(result_df)),
        "num_files": int(result_df["source_file"].nunique()),
        "k": int(args.k),
        "pass_at_1": float(result_df["pass_at_1"].mean()),
        "pass_at_k": float(result_df["pass_at_k"].mean()),
    }

    out_csv = args.out_csv
    out_dir = os.path.dirname(out_csv) or "."
    os.makedirs(out_dir, exist_ok=True)
    out_structure = os.path.join(out_dir, "summary_by_structure.csv")
    out_node_count = os.path.join(out_dir, "summary_by_node_count.csv")
    out_overall = os.path.join(out_dir, "summary_overall.json")

    summary_by_depth.to_csv(out_csv, index=False)
    summary_by_structure.to_csv(out_structure, index=False)
    summary_by_node_count.to_csv(out_node_count, index=False)
    with open(out_overall, "w", encoding="utf-8") as f:
        json.dump(overall, f, ensure_ascii=True, indent=2)

    print(f"Wrote summary_by_depth: {out_csv}")
    print(f"Wrote summary_by_structure: {out_structure}")
    print(f"Wrote summary_by_node_count: {out_node_count}")
    print(f"Wrote summary_overall: {out_overall}")

    if args.wandb_project:
        try:
            import wandb

            tags = [t.strip() for t in args.wandb_tags.split(",") if t.strip()]
            init_kwargs = {
                "project": args.wandb_project,
                "name": args.wandb_run_name or f"summary_k{args.k}",
                "config": {
                    "k": int(args.k),
                    "pred_parquet": args.pred_parquet,
                },
                "reinit": True,
            }
            if args.wandb_entity:
                init_kwargs["entity"] = args.wandb_entity
            if args.wandb_group:
                init_kwargs["group"] = args.wandb_group
            if len(tags) > 0:
                init_kwargs["tags"] = tags

            run = wandb.init(**init_kwargs)
            run.log({
                "summary/pass_at_1": overall["pass_at_1"],
                "summary/pass_at_k": overall["pass_at_k"],
                "summary/num_records": overall["num_records"],
                "summary/num_files": overall["num_files"],
            })

            depth_table = wandb.Table(dataframe=summary_by_depth)
            struct_table = wandb.Table(dataframe=summary_by_structure)
            node_count_table = wandb.Table(dataframe=summary_by_node_count)
            run.log({
                "summary/by_depth": depth_table,
                "summary/by_structure": struct_table,
                "summary/by_node_count": node_count_table,
            })

            artifact = wandb.Artifact("stage1-generalization-summary", type="analysis")
            artifact.add_file(out_csv)
            artifact.add_file(out_structure)
            artifact.add_file(out_node_count)
            artifact.add_file(out_overall)
            run.log_artifact(artifact)
            run.finish()
            print("Logged summaries to W&B.")
        except Exception as e:
            print(f"Failed to log summaries to W&B: {e}")


if __name__ == "__main__":
    main()
